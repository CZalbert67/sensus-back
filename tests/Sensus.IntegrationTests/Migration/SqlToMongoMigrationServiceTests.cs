using FluentAssertions;
using Microsoft.Extensions.Logging.Abstractions;
using NSubstitute;
using Sensus.Application.Common.Interfaces;
using Sensus.Domain.Entities;
using Sensus.Domain.Enums;
using Sensus.Infrastructure.Migration;
using Sensus.TestKit.Fakes;
using Xunit;

namespace Sensus.IntegrationTests.Migration;

public sealed class SqlToMongoMigrationServiceTests
{
    private readonly InMemoryUserRepository _userRepository = new();
    private readonly IPasswordHasher _passwordHasher = Substitute.For<IPasswordHasher>();
    private readonly NullLogger<SqlToMongoMigrationService> _logger = NullLogger<SqlToMongoMigrationService>.Instance;

    [Fact]
    public async Task MigrateInitialDataAsync_WhenUserAlreadyExists_ShouldReturnEarlyWithoutAddingUser()
    {
        // Arrange
        const string initialEmail = "oscarsa48700@gmail.com";
        var existingUser = User.Create("Oscar Jose Salinas", initialEmail, "existing-hash", true, DateTime.UtcNow).Value;
        await _userRepository.AddAsync(existingUser);

        var service = new SqlToMongoMigrationService(_userRepository, _passwordHasher, _logger);

        // Act
        await service.MigrateInitialDataAsync();

        // Assert
        _passwordHasher.DidNotReceiveWithAnyArgs().HashPassword(Arg.Any<string>());
        var userInRepo = await _userRepository.GetByEmailAsync(initialEmail);
        userInRepo.Should().NotBeNull();
        userInRepo!.PasswordHash.Should().Be("existing-hash");
    }

    [Fact]
    public async Task MigrateInitialDataAsync_WhenInitialSeedPasswordEnvVarIsConfigured_ShouldHashAndMigrateUser()
    {
        // Arrange
        const string initialEmail = "oscarsa48700@gmail.com";
        const string customPassword = "Custom_Seed_Password_2026_Secure!";
        const string expectedHash = "$2a$12$secureCustomHashGeneratedForTestPurpose";

        Environment.SetEnvironmentVariable("INITIAL_SEED_PASSWORD", customPassword);
        try
        {
            _passwordHasher.HashPassword(customPassword).Returns(expectedHash);
            var service = new SqlToMongoMigrationService(_userRepository, _passwordHasher, _logger);

            // Act
            await service.MigrateInitialDataAsync();

            // Assert
            _passwordHasher.Received(1).HashPassword(customPassword);
            var migratedUser = await _userRepository.GetByEmailAsync(initialEmail);
            migratedUser.Should().NotBeNull();
            migratedUser!.NombreCompleto.Should().Be("Oscar Jose Salinas");
            migratedUser.Correo.Should().Be(initialEmail);
            migratedUser.PasswordHash.Should().Be(expectedHash);
            migratedUser.Roles.Should().Contain(RoleType.Consumidor);
            migratedUser.Estatus.Should().BeTrue();
        }
        finally
        {
            Environment.SetEnvironmentVariable("INITIAL_SEED_PASSWORD", null);
        }
    }

    [Fact]
    public async Task MigrateInitialDataAsync_WhenInitialSeedPasswordEnvVarIsNull_ShouldGenerateRandomPasswordAndMigrateUser()
    {
        // Arrange
        const string initialEmail = "oscarsa48700@gmail.com";
        const string generatedHash = "$2a$12$randomAutoGeneratedPasswordHash";

        Environment.SetEnvironmentVariable("INITIAL_SEED_PASSWORD", null);
        _passwordHasher.HashPassword(Arg.Any<string>()).Returns(generatedHash);

        var service = new SqlToMongoMigrationService(_userRepository, _passwordHasher, _logger);

        // Act
        await service.MigrateInitialDataAsync();

        // Assert
        _passwordHasher.Received(1).HashPassword(Arg.Is<string>(pwd => !string.IsNullOrWhiteSpace(pwd) && pwd.Length >= 32));
        var migratedUser = await _userRepository.GetByEmailAsync(initialEmail);
        migratedUser.Should().NotBeNull();
        migratedUser!.Correo.Should().Be(initialEmail);
        migratedUser.PasswordHash.Should().Be(generatedHash);
        migratedUser.Roles.Should().Contain(RoleType.Consumidor);
        migratedUser.Estatus.Should().BeTrue();
    }
}
